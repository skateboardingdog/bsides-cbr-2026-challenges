# Chinese Remainder Theorem using built-in pow(x, -1, m).
def crt(remainders, moduli):
    M = prod(moduli)
    res = sum(r * (M // m) * pow(M // m, -1, m) for r, m in zip(remainders, moduli))
    return res % M

