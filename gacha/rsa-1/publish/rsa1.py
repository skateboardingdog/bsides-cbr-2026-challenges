# RSA encrypts a message m as:
#
#     c = m^e mod n
#
# where n = p * q.
#
# To decrypt it:
#
#     phi = (p - 1) * (q - 1)
#     d = e^-1 mod phi
#     m = c^d mod n
#
# Crypto.Util.number.long_to_bytes() may be useful for converting a number back to a string

from Crypto.Util.number import bytes_to_long, getPrime

FLAG = b"skbdg{????????????????????????}"
m = bytes_to_long(FLAG)

p = getPrime(256)
q = getPrime(256)
n = p * q
e = 65537
c = pow(m, e, n)

